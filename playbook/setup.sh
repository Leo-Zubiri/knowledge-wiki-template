#!/usr/bin/env bash
# playbook/setup.sh — bootstrap a CONSUMER project so any file-reading agent can use this knowledge base on it.
#
#   bash <kb>/playbook/setup.sh project <dir> [--claude] [--codex] [--all] [--mcp] [--dry-run]
#   bash <kb>/playbook/setup.sh check   <dir>
#   bash <kb>/playbook/setup.sh unlink  <dir>        # removes only the generated pointer skills
#
# Writes into <dir> ONLY files that do not exist yet (never overwrites), all of them plain text meant to be
# committed, with no absolute paths:
#   AGENTS.md (pointer)  CLAUDE.md (@AGENTS.md)  .gemini/settings.json  .env.example  .gitignore (+.env)
#   docs/project-profile.md  docs/README.md  docs/plans/
# Optional adapters so products that discover skills trigger them automatically (others follow AGENTS.md):
#   --claude  .claude/skills/<name>/SKILL.md   (Claude Code; OpenCode reads the same folder)
#   --codex   .agents/skills/<name>/SKILL.md   (Codex)
#   --all     both
#   --mcp     copies <kb>/.mcp.json.example into the project (optional Obsidian MCP; key stays out of git)
# Pointer skills are regenerable: they carry a marker line and are the only files `project` may rewrite.
# Config: <kb>/playbook/setup.conf (see setup.conf.example); defaults derive from the kb folder name.
set -euo pipefail

KB="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PB="$KB/playbook"
KB_NAME="$(basename "$KB")"
KB_ENV_VAR="KNOWLEDGE_PATH"
PROFILE_TEMPLATE="$PB/templates/consumer/project-profile.md"
SKILLS=()
[ -f "$PB/setup.conf" ] && . "$PB/setup.conf"
if [ "${#SKILLS[@]}" -eq 0 ]; then
  for d in "$PB"/skills/*/; do [ -f "$d/SKILL.md" ] && SKILLS+=("$(basename "$d")"); done
fi
MARKER="<!-- generated by ${KB_NAME}/playbook/setup.sh — regenerate with it, do not edit -->"

DRY=0; CLAUDE=0; CODEX=0; MCP=0
say()  { printf '%s\n' "$*"; }
ok()   { printf '  \033[32m✔\033[0m %s\n' "$*"; }
skip() { printf '  \033[2m·\033[0m %s (exists, skipped)\n' "$*"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

render() {  # $1 = template file; prints with placeholders replaced
  sed -e "s#{{KB_NAME}}#$KB_NAME#g" -e "s#{{KB_ENV_VAR}}#$KB_ENV_VAR#g" -e "s#{{PROJECT}}#$PROJECT#g" -e "s#{{DATE}}#$(date +%F)#g" "$1"
}
put() {  # $1 = target path (relative to PROJECT_DIR), $2 = content via stdin
  local t="$PROJECT_DIR/$1"
  if [ -e "$t" ]; then skip "$1"; cat >/dev/null; return; fi
  if [ "$DRY" = 1 ]; then ok "$1 (would create)"; cat >/dev/null; return; fi
  mkdir -p "$(dirname "$t")"; cat > "$t"; ok "$1"
}
skill_description() {  # $1 = skill name → single-line description from its SKILL.md frontmatter
  python3 - "$PB/skills/$1/SKILL.md" <<'PY'
import sys,re
t=open(sys.argv[1],encoding='utf-8').read().split('---')
fm=t[1] if len(t)>2 else ''
m=re.search(r'^description:\s*(.*)$',fm,re.M)
desc=m.group(1).strip() if m else ''
if desc in ('>-','>','|','|-',''):
    lines=[]; grab=False
    for ln in fm.splitlines():
        if ln.startswith('description:'): grab=True; continue
        if grab and (ln.startswith(' ') or ln.startswith('\t')): lines.append(ln.strip())
        elif grab: break
    desc=' '.join(lines)
print(desc.replace('\n',' '))
PY
}
write_pointer() {  # $1 = adapter root (.claude/skills | .agents/skills), $2 = skill name
  local rel="$1/$2/SKILL.md" t="$PROJECT_DIR/$1/$2/SKILL.md" desc
  desc="$(skill_description "$2")"
  if [ -e "$t" ] && ! grep -qF "$MARKER" "$t"; then skip "$rel (not generated by this script)"; return; fi
  if [ "$DRY" = 1 ]; then ok "$rel (would write pointer)"; return; fi
  mkdir -p "$(dirname "$t")"
  cat > "$t" <<EOF
---
name: $2
description: $desc
---
$MARKER

Follow the canonical procedure in the knowledge base — do not restate it here:
read \`\$$KB_ENV_VAR/playbook/skills/$2/SKILL.md\` and do what it says.
\`$KB_ENV_VAR\` comes from \`.env\`; when unset, the knowledge base is the sibling folder \`../$KB_NAME\`.
EOF
  ok "$rel"
}
ensure_line() {  # $1 = relative file, $2 = line to ensure
  local t="$PROJECT_DIR/$1"
  if [ -f "$t" ] && grep -qxF "$2" "$t"; then return; fi
  if [ "$DRY" = 1 ]; then ok "$1 += '$2' (would append)"; return; fi
  mkdir -p "$(dirname "$t")"; printf '%s\n' "$2" >> "$t"; ok "$1 += '$2'"
}
gemini_settings() {
  local t="$PROJECT_DIR/.gemini/settings.json"
  if [ -f "$t" ] && grep -q '"AGENTS.md"' "$t"; then skip ".gemini/settings.json"; return; fi
  if [ "$DRY" = 1 ]; then ok ".gemini/settings.json (would create/merge)"; return; fi
  mkdir -p "$PROJECT_DIR/.gemini"
  python3 - "$t" <<'PY'
import json,sys,pathlib
p=pathlib.Path(sys.argv[1]); d=json.loads(p.read_text()) if p.exists() else {}
ctx=d.setdefault("context",{}); names=ctx.get("fileName",[])
if isinstance(names,str): names=[names]
for n in ("AGENTS.md","GEMINI.md"):
    if n not in names: names.append(n)
ctx["fileName"]=names; p.write_text(json.dumps(d,indent=2)+"\n")
PY
  ok ".gemini/settings.json"
}

cmd_project() {
  say "bootstrapping consumer project: $PROJECT_DIR  (knowledge base: $KB_NAME, env var: $KB_ENV_VAR)"
  [ "$DRY" = 1 ] && say "  dry run — nothing is written"
  render "$PB/templates/consumer/AGENTS.md"       | put "AGENTS.md"
  printf '@AGENTS.md\n'                            | put "CLAUDE.md"
  gemini_settings
  render "$PB/templates/consumer/.env.example"    | put ".env.example"
  ensure_line ".gitignore" ".env"
  render "$PROFILE_TEMPLATE"                      | put "docs/project-profile.md"
  render "$PB/templates/consumer/docs-README.md"  | put "docs/README.md"
  printf '' | put "docs/plans/.gitkeep"
  if [ "$CLAUDE" = 1 ]; then for s in "${SKILLS[@]}"; do write_pointer ".claude/skills" "$s"; done; fi
  if [ "$CODEX"  = 1 ]; then for s in "${SKILLS[@]}"; do write_pointer ".agents/skills" "$s"; done; fi
  if [ "$MCP" = 1 ] && [ -f "$KB/.mcp.json.example" ]; then cat "$KB/.mcp.json.example" | put ".mcp.json.example"; fi
  say "done. Commit the generated files; teammates only need the knowledge base cloned (as ../$KB_NAME or via \$$KB_ENV_VAR)."
}

cmd_check() {
  say "consumer status: $PROJECT_DIR"
  for f in AGENTS.md CLAUDE.md .gemini/settings.json .env.example docs/project-profile.md docs/README.md; do
    [ -e "$PROJECT_DIR/$f" ] && ok "$f" || warn "$f missing"
  done
  local kb_resolved=""
  if [ -n "${!KB_ENV_VAR:-}" ]; then kb_resolved="${!KB_ENV_VAR}"; elif [ -f "$PROJECT_DIR/.env" ] && grep -q "^$KB_ENV_VAR=" "$PROJECT_DIR/.env"; then kb_resolved="$(grep "^$KB_ENV_VAR=" "$PROJECT_DIR/.env" | tail -1 | cut -d= -f2-)"; elif [ -d "$PROJECT_DIR/../$KB_NAME" ]; then kb_resolved="$PROJECT_DIR/../$KB_NAME (sibling default)"; fi
  [ -n "$kb_resolved" ] && ok "knowledge base reachable: $kb_resolved" || warn "knowledge base not reachable: set $KB_ENV_VAR in .env or clone it as ../$KB_NAME"
  for root in .claude/skills .agents/skills; do
    [ -d "$PROJECT_DIR/$root" ] || continue
    local n=0; for s in "${SKILLS[@]}"; do [ -f "$PROJECT_DIR/$root/$s/SKILL.md" ] && n=$((n+1)); done
    [ "$n" = "${#SKILLS[@]}" ] && ok "$root: ${#SKILLS[@]}/${#SKILLS[@]} pointer skills" || warn "$root: $n/${#SKILLS[@]} pointer skills (re-run 'project' to regenerate)"
  done
}

cmd_unlink() {
  say "removing generated pointer skills from $PROJECT_DIR"
  for root in .claude/skills .agents/skills; do
    for s in "${SKILLS[@]}"; do
      local t="$PROJECT_DIR/$root/$s/SKILL.md"
      if [ -f "$t" ] && grep -qF "$MARKER" "$t"; then rm -f "$t"; rmdir "$(dirname "$t")" 2>/dev/null || true; ok "$root/$s"; fi
    done
    rmdir "$PROJECT_DIR/$root" 2>/dev/null || true
  done
}

CMD="${1:-}"; shift || true
PROJECT_DIR="${1:-}"; [ -n "$PROJECT_DIR" ] && shift || true
for a in "$@"; do case "$a" in
  --claude) CLAUDE=1 ;; --codex) CODEX=1 ;; --all) CLAUDE=1; CODEX=1 ;; --mcp) MCP=1 ;; --dry-run) DRY=1 ;;
  *) die "unknown option: $a" ;; esac; done
case "$CMD" in
  project|check|unlink)
    [ -n "$PROJECT_DIR" ] || die "usage: setup.sh $CMD <dir> [options]"
    [ -d "$PROJECT_DIR" ] || { [ "$DRY" = 1 ] || mkdir -p "$PROJECT_DIR"; }
    PROJECT_DIR="$(cd "$PROJECT_DIR" 2>/dev/null && pwd || echo "$PROJECT_DIR")"; PROJECT="$(basename "$PROJECT_DIR")"
    "cmd_$CMD" ;;
  *) say "usage: setup.sh project <dir> [--claude] [--codex] [--all] [--mcp] [--dry-run] | check <dir> | unlink <dir>"; exit 2 ;;
esac
